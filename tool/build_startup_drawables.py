"""Convert the approved sprite to an Android AnimatedVectorDrawable + matching atlas.

Original deposit poses plus generated coin-retrieval poses share one timeline.
Shared palette pixels become horizontal vector runs so Android can animate on
its render thread and honor animator duration scale.
Requires Pillow. Run `python3 tool/build_startup_drawables.py` from the repo.
The 50% inset compensates for Android's 1.5x foreground expansion:
192dp icon view * 1.5 * .5 = the same 144dp art used by Flutter.
"""
from collections import defaultdict
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "android/app/src/main/res"
SOURCE = ROOT / "assets/startup/coin-deposit.webp"
BRIDGE = ROOT / "design/startup/coin-reset-bridge-v1.png"
DURATIONS = [240, 160, 160, 120, 100, 120, 120, 180, 200, 200, 260, 640,
             80, 100, 120, 120, 120, 120, 120, 120]
ASSET = "assets/startup/coin-loop-native.png"
COLUMNS = 4
ROWS = 5
CELL = 181
TOTAL = sum(DURATIONS)


def cell_at(image, index, columns, rows):
    return image.crop((round(index % columns * image.width / columns),
                       round(index // columns * image.height / rows),
                       round((index % columns + 1) * image.width / columns),
                       round((index // columns + 1) * image.height / rows)))


def opaque_bounds(frame):
    return frame.getchannel("A").point(lambda a: 255 if a > 128 else 0).getbbox()


def build_atlas():
    source = Image.open(SOURCE).convert("RGBA")
    poses = [cell_at(source, i, 4, 3).resize((CELL, CELL), Image.Resampling.NEAREST)
             for i in range(12)]
    bridge = Image.open(BRIDGE).convert("RGBA")
    start_bounds, end_bounds = opaque_bounds(poses[-1]), opaque_bounds(poses[0])
    for index in range(7):
        frame = cell_at(bridge, index, 4, 2)
        bounds = opaque_bounds(frame)
        # Register exported cells to the existing group's bounds. This only
        # adjusts scale/placement; all new drawing comes from the generated art.
        progress = index / 7
        target = [a + (b - a) * progress for a, b in zip(start_bounds, end_bounds)]
        sx = (bounds[2] - bounds[0]) / (target[2] - target[0])
        sy = (bounds[3] - bounds[1]) / (target[3] - target[1])
        poses.append(frame.transform(
            (CELL, CELL), Image.Transform.AFFINE,
            (sx, 0, bounds[0] - target[0] * sx,
             0, sy, bounds[1] - target[1] * sy),
            Image.Resampling.NEAREST,
        ))
    # Use the exact first pixels at the wrap, rather than an approximate redraw.
    poses.append(poses[0].copy())
    atlas = Image.new("RGBA", (CELL * COLUMNS, CELL * ROWS))
    for index, frame in enumerate(poses):
        atlas.paste(frame, (index % COLUMNS * CELL, index // COLUMNS * CELL))
    return atlas.quantize(colors=96, method=Image.Quantize.FASTOCTREE,
                          dither=Image.Dither.NONE).convert("RGBA")


def write_timeline():
    elapsed = 0
    ends = []
    for duration in DURATIONS:
        elapsed += duration
        ends.append(f"    {elapsed},")
    (ROOT / "lib/widgets/coin_loading_timeline.dart").write_text(
        "// Generated by tool/build_startup_drawables.py; do not edit by hand.\n"
        "abstract final class CoinLoadingTimeline {\n"
        f"  static const asset = '{ASSET}';\n"
        f"  static const columns = {COLUMNS};\n"
        f"  static const rows = {ROWS};\n"
        f"  static const duration = Duration(milliseconds: {TOTAL});\n"
        "  static const frameEnds = [\n" + "\n".join(ends) + "\n  ];\n}\n"
    )
    (RES / "values/startup_motion.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/build_startup_drawables.py. -->\n'
        '<resources>\n'
        f'    <integer name="startup_cycle_duration">{TOTAL}</integer>\n'
        '</resources>\n'
    )


def paths_for(frame):
    pixels = frame.load()
    paths = defaultdict(list)
    for y in range(CELL):
        x = 0
        while x < CELL:
            color = pixels[x, y]
            end = x + 1
            while end < CELL and pixels[end, y] == color:
                end += 1
            if color[3]:
                width = end - x
                paths[color].append(f"M{x},{y}h{width}v1h-{width}z")
            x = end
    return paths


def main():
    atlas = build_atlas()
    atlas.save(ROOT / ASSET, optimize=True)
    write_timeline()
    assert cell_at(atlas, 0, COLUMNS, ROWS).tobytes() == cell_at(
        atlas, len(DURATIONS) - 1, COLUMNS, ROWS).tobytes()
    frames = RES / "drawable-nodpi"
    frames.mkdir(exist_ok=True)
    vector = []
    targets = []
    start = 0
    for index, duration in enumerate(DURATIONS):
        frame = cell_at(atlas, index, COLUMNS, ROWS)
        # Pre-Android-12 launch window uses the same first pose at 144dp.
        if index == 0:
            frame.save(frames / "startup_cat_00.png", optimize=True)
        else:
            (frames / f"startup_cat_{index:02d}.png").unlink(missing_ok=True)
        vector.append(f'            <group android:name="frame_{index}" android:translateX="{0 if index == 0 else 1000}">')
        for (red, green, blue, alpha), runs in paths_for(frame).items():
            vector.append(
                f'                <path android:fillColor="#{red:02x}{green:02x}{blue:02x}" '
                f'android:fillAlpha="{alpha / 255:.6f}" android:pathData="{"".join(runs)}" />'
            )
        vector.append('            </group>')
        # Offscreen groups are clipped, avoiding rasterizing all poses at once.
        # A one-millisecond switch makes discrete frames. A single animator per
        # frame avoids competing delayed animators targeting the same property.
        end = start + duration
        keys = [(0, 1 if index == 0 else 0)]
        if start:
            keys.extend([(start - 1, 0), (start, 1)])
        if index < len(DURATIONS) - 1:
            keys.extend([(end - 1, 1), (end, 0), (TOTAL, 0)])
        else:
            keys.append((TOTAL, 1))
        keyframes = '\n'.join(
            f'                    <keyframe android:fraction="{time / TOTAL:.6f}" android:value="{0 if value else 1000}" />'
            for time, value in keys
        )
        targets.append(f'''    <target android:name="frame_{index}">
        <aapt:attr name="android:animation">
            <objectAnimator android:duration="{TOTAL}" android:repeatCount="infinite" android:repeatMode="restart" android:interpolator="@interpolator/startup_frames">
                <propertyValuesHolder android:propertyName="translateX" android:valueType="floatType">
{keyframes}
                </propertyValuesHolder>
            </objectAnimator>
        </aapt:attr>
    </target>''')
        start = end
    (RES / "drawable/startup_cat_motion.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/build_startup_drawables.py; do not edit by hand. -->\n'
        '<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt">\n'
        '    <aapt:attr name="android:drawable">\n'
        '        <vector android:width="288dp" android:height="288dp" android:viewportWidth="362" android:viewportHeight="362">\n'
        '            <group android:translateX="90.5" android:translateY="90.5">\n'
        + '\n'.join(vector)
        + '\n            </group>\n        </vector>\n    </aapt:attr>\n'
        + '\n'.join(targets) + '\n</animated-vector>\n'
    )
    # RT samples complex property keyframes internally. Select the middle of
    # each pose's interval with a stepped time interpolator, so those samples
    # cannot briefly slide a half-drawn pose across the screen at a boundary.
    steps = ["M0,0"]
    elapsed = 0
    previous = 0.0
    for index, duration in enumerate(DURATIONS[:-1]):
        elapsed += duration
        x = elapsed / TOTAL
        y = (elapsed + DURATIONS[index + 1] / 2) / TOTAL
        if index == len(DURATIONS) - 2:
            y = 1.0
        steps.extend([f"L{x:.6f},{previous:.6f}", f"L{x:.6f},{y:.6f}"])
        previous = y
    steps.append("L1,1")
    interpolators = RES / "interpolator"
    interpolators.mkdir(exist_ok=True)
    (interpolators / "startup_frames.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/build_startup_drawables.py. Discrete sprite poses. -->\n'
        '<pathInterpolator xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:pathData="{" ".join(steps)}" />\n'
    )
    print(f'Generated {len(DURATIONS)} poses, {TOTAL}ms cycle; seam pixels match exactly.')


if __name__ == "__main__":
    main()
