"""Validate six-pose atlases and regenerate shared source rectangles.

Run with Python + Pillow from any directory. Only layout.json and the Dart
metadata are written; generated artwork is never modified. Pose boundaries
follow transparent valleys near the expected 3-by-2 grid, preserving tails
and accessories that extend beyond a cell's nominal edge.
"""

import json
from pathlib import Path

from PIL import Image


REPO = Path(__file__).resolve().parents[1]
ATLAS_ROOT = REPO / "assets/costumes/autumn_2026"


def split_near(projection, expected, radius):
    candidates = range(
        max(1, int(expected - radius)),
        min(len(projection) - 1, int(expected + radius)),
    )
    boundary = min(candidates, key=lambda n: (projection[n], abs(n - expected)))
    # A separator may meet anti-aliased edge pixels but must not cross a body.
    assert projection[boundary] <= 3, (expected, boundary, projection[boundary])
    return boundary


def inspect_atlas(path):
    with Image.open(path) as image:
        assert image.mode == "RGBA", path
        alpha = image.getchannel("A")
        assert alpha.getextrema() == (0, 255), path
        mask = alpha.point(lambda value: 255 if value >= 64 else 0)
        width, height = image.size
        pixels = mask.load()
        row_sums = [
            sum(pixels[x, y] > 0 for x in range(width)) for y in range(height)
        ]
        middle = split_near(row_sums, height / 2, height * 0.08)
        frames = []
        for y0, y1 in [(0, middle), (middle, height)]:
            col_sums = [
                sum(pixels[x, y] > 0 for y in range(y0, y1))
                for x in range(width)
            ]
            first = split_near(col_sums, width / 3, width * 0.07)
            second = split_near(col_sums, width * 2 / 3, width * 0.07)
            for x0, x1 in [(0, first), (first, second), (second, width)]:
                bounds = mask.crop((x0, y0, x1, y1)).getbbox()
                assert bounds, (path, "empty pose")
                assert bounds[2] - bounds[0] > width * 0.12, (path, bounds)
                assert bounds[3] - bounds[1] > height * 0.2, (path, bounds)
                left = max(x0, x0 + bounds[0] - 2)
                top = max(y0, y0 + bounds[1] - 2)
                right = min(x1, x0 + bounds[2] + 2)
                bottom = min(y1, y0 + bounds[3] + 2)
                frames.append([
                    round(left / width, 8),
                    round(top / height, 8),
                    round((right - left) / width, 8),
                    round((bottom - top) / height, 8),
                ])
        print(f"{path.stem}: {image.size}, six transparent role poses")
        return {"size": [width, height], "frames": frames}


def main():
    layouts = {
        path.stem: inspect_atlas(path) for path in sorted(ATLAS_ROOT.glob("*.png"))
    }
    assert len(layouts) == 12, len(layouts)
    (ATLAS_ROOT / "layout.json").write_text(
        json.dumps(layouts, indent=2) + "\n", encoding="utf-8"
    )
    lines = [
        "// Generated by tool/inspect_costume_atlases.py; artwork is not altered.",
        "// Atlas reading order: idle, activity, processing, positive, success, warning.",
        "import 'dart:ui';",
        "",
        "const costumeAtlasFrames = <String, List<Rect>>{",
    ]
    for character_id, data in layouts.items():
        lines.append(f"  '{character_id}': [")
        for frame in data["frames"]:
            lines.append("    Rect.fromLTWH(" + ", ".join(map(str, frame)) + "),")
        lines.append("  ],")
    lines.append("};")
    (REPO / "lib/data/costume_atlas_layout.dart").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )


if __name__ == "__main__":
    main()
